// Plugin de SPM build-tool que genera Generated/AuditCodes.generated.swift.
// El archivo generado contiene un `enum AuditCode` con constantes y un
// `extension` con un set `all`. Si la plataforma no importa
// `FoundationNetworking` (trampa P4), el archivo se genera con un comentario
// `// noop` y un único case `noop` para no romper la compilacion del
// consumidor (FxSwiftServer).
import Foundation
import PackagePlugin

@main
struct AuditCodesPlugin: BuildToolPlugin {
    func createBuildCommands(
        context: PluginContext,
        target: Target
    ) async throws -> [BuildCommand] {
        // Solo emitimos un comando si el target es FxSwiftServer.
        guard target.name == "FxSwiftServer" else {
            return []
        }
        // Salida que sera generada. El consumidor la importa implicitamente
        // al estar en su `Generated/` (no requiere import explicito).
        let output = context.pluginWorkDirectory.appending("AuditCodes.generated.swift")
        return [
            .buildCommand(
                displayName: "Generate AuditCodes",
                executable: .path("/bin/sh"),
                arguments: [
                    "-c",
                    """
                    if [ -z \"$(swift --version 2>/dev/null | head -n1)\" ]; then \
                      mkdir -p \"\(output.removingLastComponent().string)\"
                    fi
                    cat > \"\(output.string)\" <<'GEN_EOF'
                    // AUTO-GENERATED by AuditCodesPlugin (F06ab). DO NOT EDIT.
                    #if canImport(FoundationNetworking)
                    public enum AuditCode: String, Sendable, CaseIterable {
                        case unverified
                        case stale
                        case orphaned
                        case archived
                    }
                    #else
                    public enum AuditCode: String, Sendable, CaseIterable {
                        // noop: FoundationNetworking ausente (trampa P4)
                        case noop
                    }
                    #endif
                    GEN_EOF
                    """
                ],
                environment: [:],
                inputFiles: [],
                outputFiles: [output]
            )
        ]
    }
}